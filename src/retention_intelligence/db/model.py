
from sqlalchemy import (
    Column,
    Integer,
    String,
    Float,
    DateTime,
    JSON,
    Index
)
from sqlalchemy.sql import func

from retention_intelligence.db.connection import Base


# ---------------------------------
# 1. Telco ML Churn Prediction
# ---------------------------------

class TelcoChurnPrediction(Base):

    __tablename__ = "telco_churn_predictions"

    id = Column(Integer, primary_key=True, index=True)

    customer_id = Column(String(50), nullable=False, index=True)

    churn_prediction = Column(Integer, nullable=False)
    churn_probability = Column(Float, nullable=False)

    risk_level = Column(String(20), nullable=False)

    key_factors = Column(JSON, nullable=True)

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now()
    )


# ---------------------------------
# 2. Olist Retention Risk
# ---------------------------------

class OlistRetentionRisk(Base):

    __tablename__ = "olist_retention_risks"

    id = Column(Integer, primary_key=True, index=True)

    customer_id = Column(String(100), nullable=False, index=True)

    total_orders = Column(Integer, nullable=False)
    delivered_orders = Column(Integer, nullable=False)
    cancelled_orders = Column(Integer, nullable=False)

    last_order_date = Column(DateTime, nullable=True)

    average_order_value = Column(Float, nullable=False)

    days_since_last_order = Column(Integer, nullable=False)

    retention_risk_proxy = Column(String(30), nullable=False)

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now()
    )


# ---------------------------------
# 3. Retention Recommendations
# ---------------------------------

class RetentionRecommendation(Base):

    __tablename__ = "retention_recommendations"

    id = Column(Integer, primary_key=True, index=True)

    source = Column(String(20), nullable=False)

    customer_id = Column(String(50), nullable=False, index=True)

    risk_type = Column(String(30), nullable=False)

    risk_level = Column(String(20), nullable=False)

    recommended_action = Column(String(255), nullable=False)

    reasoning = Column(JSON, nullable=True)

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now()
    )


# ---------------------------------
# 4. Complete Retention Audit Log
# ---------------------------------

class RetentionAuditLog(Base):

    __tablename__ = "retention_audit_logs"

    id = Column(Integer, primary_key=True, index=True)

    # Customer information
    customer_id = Column(String(100), nullable=False, index=True)

    source = Column(String(20), nullable=False)

    # Investigation status
    investigation_status = Column(
        String(30),
        nullable=False,
        default="started"
    )

    # Churn prediction result
    churn_prediction = Column(JSON, nullable=True)

    # Retention strategy generated by agent
    retention_strategy = Column(JSON, nullable=True)

    # Decision Engine result
    policy_result = Column(JSON, nullable=True)

    # Human approval result
    human_approval = Column(JSON, nullable=True)

    # Execution result
    execution_result = Column(JSON, nullable=True)

    # Errors generated during workflow
    errors = Column(JSON, nullable=True)

    # Timestamps
    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False
    )

    __table_args__ = (
        Index(
            "idx_retention_audit_customer_source",
            "customer_id",
            "source"
        ),
    )
